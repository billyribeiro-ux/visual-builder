import type { DesignTokens } from '@app-viz/schema';

export function generateAppCss(tokens: DesignTokens): string {
  const colorVars = Object.entries(tokens.colors || {})
    .map(([key, val]) => `  --token-${key}: ${val};`)
    .join('\n');

  const radiusVars = Object.entries(tokens.radii || {})
    .map(([key, val]) => `  --token-radius-${key}: ${val};`)
    .join('\n');

  const shadowVars = Object.entries(tokens.shadows || {})
    .map(([key, val]) => `  --token-shadow-${key}: ${val};`)
    .join('\n');

  const spacingVars = Object.entries(tokens.spacing || {})
    .map(([key, val]) => `  --token-spacing-${key}: ${val};`)
    .join('\n');

  return `/* Generated by Visual App Builder on 2026-10-25 */
@import "tailwindcss";

@theme {
  --color-primary: var(--token-primary);
  --color-primary-hover: var(--token-primary-hover);
  --color-primary-foreground: var(--token-primary-foreground);
  --color-secondary: var(--token-secondary);
  --color-secondary-hover: var(--token-secondary-hover);
  --color-secondary-foreground: var(--token-secondary-foreground);
  --color-background: var(--token-background);
  --color-foreground: var(--token-foreground);
  --color-muted: var(--token-muted);
  --color-muted-foreground: var(--token-muted-foreground);
  --color-accent: var(--token-accent);
  --color-accent-foreground: var(--token-accent-foreground);
  --color-card: var(--token-card);
  --color-card-foreground: var(--token-card-foreground);
  --color-border: var(--token-border);
  --color-ring: var(--token-ring);
  --color-destructive: var(--token-destructive);
  --color-success: var(--token-success);

  --font-heading: var(--token-font-heading);
  --font-body: var(--token-font-body);
  --font-mono: var(--token-font-mono);

  --radius-sm: var(--token-radius-sm);
  --radius-md: var(--token-radius-md);
  --radius-lg: var(--token-radius-lg);
  --radius-xl: var(--token-radius-xl);
  --radius-2xl: var(--token-radius-2xl);
  --radius-full: var(--token-radius-full);
}

:root {
${colorVars}
  --token-font-heading: ${tokens.fonts?.heading || 'sans-serif'};
  --token-font-body: ${tokens.fonts?.body || 'sans-serif'};
  --token-font-mono: ${tokens.fonts?.mono || 'monospace'};
${radiusVars}
${shadowVars}
${spacingVars}
}

body {
  font-family: var(--font-body);
  background-color: var(--color-background);
  color: var(--color-foreground);
  margin: 0;
  padding: 0;
  -webkit-font-smoothing: antialiased;
}

h1, h2, h3, h4, h5, h6 {
  font-family: var(--font-heading);
}
`;
}
